age = 19                  # integer
height = 5.0              # float
a = 3,4                   # tuple
z, y, x = "ORANGE", "BANANA", "APPLE"  # multiple assignment
f = int(2.567)            # converts float to int → 2
j = float(3)              # converts int to float → 3.0
w = float(4.5)            # float stays float → 4.5
o = str("Hello")          # string conversion
d = b = c = "PINK"        # one value to multiple variables
user_fav_colour = input("Enter a colour: ")  # user input
h = "KLH-BOWRAMPET"       # string for slicing
u = "KONERU LAKSHMAIAH EDUCATIONAL FOUNDATION" # string for slicing

print(u[-10:-4])          # prints characters from index -10 to -5 → "TATION"
print(h[2:5])             # prints characters from index 2 to 4 → "H-B"
print(name)               # prints "Yasaswi"
print(age)                # prints 19
print(height)             # prints 5.0
print(type(height))       # prints <class 'float'>
print(a)                  # prints (3, 4)
print(z, y, x)            # prints ORANGE BANANA APPLE
print(d)                  # prints PINK
